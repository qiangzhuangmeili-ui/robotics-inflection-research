def check_all(analyser=None):
    """返回未通过的反例清单；空列表表示全部通过。"""
    import evidence_scope as _es
    an = analyser or _es.analyse
    bad = []
    for txt, exp_a, exp_e, exp_c, why in CASES:
        p = an({"evidence": txt, "method": "T"})
        if (p.affirmed, p.excluded, p.conflict) != (exp_a, exp_e, exp_c):
            bad.append({"case": why, "text": txt,
                        "got": _es.polarity_str(p),
                        "want": "affirmed=%s|excluded=%s|conflict=%s" % (
                            ",".join(sorted(exp_a)) or "-",
                            ",".join(sorted(exp_e)) or "-",
                            ",".join(sorted(exp_c)) or "-")})
    return bad
